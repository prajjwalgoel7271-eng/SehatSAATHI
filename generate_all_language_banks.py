def build_files():
    for code, data in LANGDATA.items():
        lang_dir = os.path.join(CONTENT_DIR, code)
        os.makedirs(lang_dir, exist_ok=True)

        # 1. questionnaire.json
        q_json = {
            "language": data["name"],
            "code": code,
            "questions": [
                {
                    "id": f"q{idx+1}",
                    "text": item[0],
                    "options": [
                        {"text": item[1][0], "score": 0},
                        {"text": item[1][1], "score": 1},
                        {"text": item[1][2], "score": 2}
                    ]
                }
                for idx, item in enumerate(data["q"])
            ]
        }
        with open(os.path.join(lang_dir, 'questionnaire.json'), 'w', encoding='utf-8') as f:
            json.dump(q_json, f, ensure_ascii=False, indent=2)

        # 2. ran_items.json
        ran = data["ran"]
        ran_json = {
            "language": data["name"],
            "code": code,
            "grids": [
                {
                    "type": "letters",
                    "title": f"Rapid Letter Naming ({data['name']})",
                    "instruction": "Name each letter aloud as quickly and accurately as you can.",
                    "script": "Vernacular",
                    "items": ran["letters"],
                    "target_words": ran["letters"]
                },
                {
                    "type": "digits",
                    "title": f"Rapid Digit Naming ({data['name']})",
                    "instruction": "Name each digit aloud as fast as possible.",
                    "script": "Vernacular Numeric",
                    "items": ran["digits_display"],
                    "target_words": ran["digits_target"]
                },
                {
                    "type": "colors",
                    "title": f"Rapid Color Naming ({data['name']})",
                    "instruction": "Name the color of each box aloud as fast as possible.",
                    "script": "Visual",
                    "items": ["#e74c3c", "#3498db", "#2ecc71", "#f1c40f", "#9b59b6", "#e67e22"],
                    "target_words": ran["colors"]
                },
                {
                    "type": "objects",
                    "title": f"Rapid Object Naming ({data['name']})",
                    "instruction": "Name each object picture aloud as quickly as you can.",
                    "script": "Visual",
                    "items": ["⭐", "🍎", "🐱", "🚗", "🔑", "⚽"],
                    "target_words": ran["objects"]
                }
            ]
        }
        with open(os.path.join(lang_dir, 'ran_items.json'), 'w', encoding='utf-8') as f:
            json.dump(ran_json, f, ensure_ascii=False, indent=2)

        # 3. phonological_tasks.json
        diffs = ["easy", "easy", "easy", "medium", "medium", "medium", "hard", "hard"]
        types = ["rhyme_match", "rhyme_match", "first_sound", "last_sound", "sound_blending", "sound_segmentation", "odd_one_out", "odd_one_out"]
        p_json = {
            "language": data["name"],
            "code": code,
            "tasks": [
                {
                    "id": f"p{idx+1}",
                    "type": types[idx],
                    "prompt": item[0],
                    "options": item[1],
                    "correct": item[2],
                    "difficulty": diffs[idx]
                }
                for idx, item in enumerate(data["p"])
            ]
        }
        with open(os.path.join(lang_dir, 'phonological_tasks.json'), 'w', encoding='utf-8') as f:
            json.dump(p_json, f, ensure_ascii=False, indent=2)

        # 4. nonwords.json
        ndiffs = ["easy", "easy", "easy", "medium", "medium", "medium", "hard", "hard"]
        n_json = {
            "language": data["name"],
            "code": code,
            "items": [
                {
                    "id": f"n{idx+1}",
                    "nonword": item[0],
                    "phoneme_target": item[1],
                    "difficulty": ndiffs[idx]
                }
                for idx, item in enumerate(data["nonwords"])
            ]
        }
        with open(os.path.join(lang_dir, 'nonwords.json'), 'w', encoding='utf-8') as f:
            json.dump(n_json, f, ensure_ascii=False, indent=2)

        # 5. reading_passages.json
        s_json = {
            "language": data["name"],
            "code": code,
            "sentences": [
                {"id": "s1", "text": data["sentences"][0], "word_count": len(data["sentences"][0].split()), "difficulty": "easy"},
                {"id": "s2", "text": data["sentences"][1], "word_count": len(data["sentences"][1].split()), "difficulty": "medium"}
            ],
            "passage": {
                "title": data["passage"]["title"],
                "text": data["passage"]["text"],
                "total_words": len(data["passage"]["text"].split())
            }
        }
        with open(os.path.join(lang_dir, 'reading_passages.json'), 'w', encoding='utf-8') as f:
            json.dump(s_json, f, ensure_ascii=False, indent=2)

        # 6. spelling_words.json
        sp_json = {
            "language": data["name"],
            "code": code,
            "words": [
                {"target": w, "type": "real" if idx < 5 else "pseudo"}
                for idx, w in enumerate(data["spelling"])
            ]
        }
        with open(os.path.join(lang_dir, 'spelling_words.json'), 'w', encoding='utf-8') as f:
            json.dump(sp_json, f, ensure_ascii=False, indent=2)

        print(f"[OK] Generated all 6 JSON content banks for {data['name']} ({code})")


if __name__ == "__main__":
    build_files()
